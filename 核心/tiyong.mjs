  const 差 = Number((pt.占比 - pz.占比).toFixed(1));
  const 势不敌 = 差 >= 15;
  const 临界 = 差 >= 8 && 差 < 15;
  加('势足以敌（不被反克）', !势不敌,
    `被制者${T}占 ${pt.占比}%，制者${Z}占 ${pz.占比}%（差 ${差} 个百分点）`
    + (势不敌 ? ' ⇒ **势不敌**，不但不能制，**反被反克**'
      : 临界 ? ' ⇒ 势可相敌，但**已近临界**（阈值 15 个百分点，为引擎操作化），两说宜并陈'
        : ' ⇒ 势可相敌'),
    '《神峰通考》「木多金少，不能制伏」；《八字提要》B13「火旺可制水」（阈值 15% 为引擎操作化）');

  // 5 湿土不能制水
  let 湿土忌 = false;
