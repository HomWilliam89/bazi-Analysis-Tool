    // 只算**牵涉岁运**的合／局，否则会把原局内部的合（如巳申合化水）误记到岁运头上
    const 涉岁运 = (s) => String(s ?? '').includes('大运');
    const 成局 = (rr.地支三合 ?? [])
      .filter((x) => 涉岁运(x.positions) && String(x.局 ?? '').includes(克用神者)).map((x) => x.局);
    const 半合 = (rr.地支六合 ?? [])
      .filter((x) => 涉岁运(x.pair) && String(x.化 ?? '').includes(克用神者)).map((x) => x.pair);
    const 条 = [];
    // ⛔ 规格 §四 禁令：「**禁止把「用神合忌神」读成用神被坏**——先辨体用，再定合的方向」。
    // 故岁运干若与用神之干**相合**，不得径判"直克"：须按"用神合忌神＝把忌神锁住＝做功"处理，
    // 并陈《子平真诠》"合而不化，逢吉不为吉"的反对说；只有"冲／无合之克"才作直克。
    const 用神干字 = 用神落点.filter((o) => o.层 === '天干').map((o) => o.字);
    const 用神支字 = 用神落点.filter((o) => o.层 !== '天干').map((o) => o.字);
