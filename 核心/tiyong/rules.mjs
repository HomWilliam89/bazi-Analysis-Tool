      通关神: X, 手段, 择优: 优,
      结论: 优
                ? `${优.净判 === '**最好用**' ? '本对**最好用**的手段' : '本对**最优（但有代价）**的手段'}＝**${优.五行}**（${优.手段}，${优.净判}）；`
          + `其余${手段.filter((m) => m !== 优).map((m) => `${m.五行}（${m.净判}）`).join('、')}。`
        : `本对**无好用手段**（${候选.length ? 候选.map((m) => `${m.五行}：${m.净判}`).join('、') : '候选皆不在局'}）`
