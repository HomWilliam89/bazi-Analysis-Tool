  //   故若「克用神者」是财／官杀／食伤，**它根本不在上面两组里**——必须单独补报，
  //   否则出现"结构分析说某某本色为忌、结论却一字不提"的静默漏判。
    // ⚠ 2026-10-04 修正：旧式只认"已证"档，**非印比的暗藏档拆点**（规格 §一之二（八）二之二明定本色为忌）
  //   被排除 ⇒ 既不进结论、也不进交叉裁决（静默漏判）。今纳入暗藏两档，仍排除"口径矛盾／拆不到支柱"。
  const 印外行 = (结构分析?.全盘判忌 ?? []).filter((r) => /^本色为忌（(已证拆到支柱|暗藏·[轻重])）$/.test(String(r.状态)) && !r.在原印比循环内);
