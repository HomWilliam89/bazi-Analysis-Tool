function 制力标题(力) {
  const t = String(力?.结论 ?? '').replace(/\*\*/g, '').split('：')[0].trim();
  return `**${t || '未判'}**`;
}

/** 制力判定的**理由**：优先列致命伤；无致命伤则取结论自陈的理由（截断），**不再用 `程度` 顶替**。 */
function 制力尾部(力) {
  if (Array.isArray(力?.致命伤) && 力.致命伤.length) return `致命伤：${力.致命伤.join('、')}`;
  const s = String(力?.结论 ?? '').replace(/\*\*/g, '');
  const i = s.indexOf('：');
  return (i >= 0 ? s.slice(i + 1) : s).replace(/。$/, '').slice(0, 80);
}

