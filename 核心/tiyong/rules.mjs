  // 「合」不需要力度门槛（规格 §四：合是牵住他，不是压住他）
  if (忌被合.length) 有效护卫.push({ 途径: '合', 合: 忌被合 });

  const 危 = 隔路.贴身可直克;
  const 护神名 = [...new Set([...隔落点, ...制落点].map(护神显示))];

