  // 去重：同一支的**不同气**要分开算（年支巳以本气丙当隔护，又以中气庚当制护），
  // 但**同一支同一气**会因多条路径重复入选（旧实现实测年支巳重复 3 次）。
  // 故键取「宫位|字|层|五行」，显示时带上藏干（本丙／中庚），避免读成重复项。
  const 护神表 = new Map();
